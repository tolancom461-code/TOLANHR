-- تحضير للتنفيذ اليدوي بواسطة مالك قاعدة البيانات فقط. لم يُنفذ هذا الملف بواسطة Codex.
-- بعد المراجعة، أنشئ هذا الجدول قبل نشر الكود المعتمد عليه. لا تستخدم db:push لهذا التغيير.
CREATE TABLE `operational_transfer_requests` (
  `id` int NOT NULL AUTO_INCREMENT,
  `worker_id` int NOT NULL,
  `work_date` date NOT NULL,
  `source_group_id` int NOT NULL,
  `source_cost_center_id` int NOT NULL,
  `to_group_id` int NOT NULL,
  `to_cost_center_id` int NOT NULL,
  `status` enum('pending','approved','completed','rejected','cancelled') NOT NULL DEFAULT 'pending',
  `requested_by` int NOT NULL,
  `reviewed_by` int NULL,
  `reviewed_at` timestamp NULL,
  `rejection_reason` varchar(500) NULL,
  `completed_by` int NULL,
  `completed_at` timestamp NULL,
  `restaurant_id` int NULL,
  `finance_ready` tinyint NOT NULL DEFAULT 0,
  `active_key` varchar(64) NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_operational_transfer_active_key` (`active_key`),
  KEY `idx_operational_transfer_source_date` (`source_cost_center_id`, `work_date`),
  KEY `idx_operational_transfer_target_date` (`to_cost_center_id`, `work_date`),
  KEY `idx_operational_transfer_worker_date` (`worker_id`, `work_date`),
  KEY `idx_operational_transfer_status_date` (`status`, `work_date`),
  CONSTRAINT `otr_worker_fk` FOREIGN KEY (`worker_id`) REFERENCES `workers` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `otr_source_group_fk` FOREIGN KEY (`source_group_id`) REFERENCES `groups` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `otr_source_center_fk` FOREIGN KEY (`source_cost_center_id`) REFERENCES `cost_centers` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `otr_to_group_fk` FOREIGN KEY (`to_group_id`) REFERENCES `groups` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `otr_to_center_fk` FOREIGN KEY (`to_cost_center_id`) REFERENCES `cost_centers` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `otr_requested_by_fk` FOREIGN KEY (`requested_by`) REFERENCES `users` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `otr_reviewed_by_fk` FOREIGN KEY (`reviewed_by`) REFERENCES `users` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `otr_completed_by_fk` FOREIGN KEY (`completed_by`) REFERENCES `users` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `otr_restaurant_fk` FOREIGN KEY (`restaurant_id`) REFERENCES `restaurants` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
);
